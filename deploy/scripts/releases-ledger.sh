#!/bin/sh
# Writes docs/RELEASES.md to stdout from GitHub's own record (docs/plan-deploy.md §4a):
# every PR merged into dev, its labels (verified-on-dev, needs-flag, shipped) and the
# promotion PRs merged into release (branches promote/*, which list their PRs in a
# "<!-- promote-prs: ... -->" line). The ledger is generated, never hand-edited, so it
# can't drift from the labels; promote-release.yml regenerates it after each promotion.
#
#   deploy/scripts/releases-ledger.sh [owner/repo] > docs/RELEASES.md
#
# Needs gh (signed in, or GH_TOKEN) and jq.
set -eu
repo="${1:-${GITHUB_REPOSITORY:-Nkr1shna/margin}}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

gh pr list --repo "$repo" --base dev --state merged --limit 1000 \
  --json number,title,mergedAt,labels > "$tmp/dev.json"
gh pr list --repo "$repo" --base release --state merged --limit 1000 \
  --json number,mergedAt,headRefName,body > "$tmp/release.json"

cat <<'EOF'
# Releases

Generated by `deploy/scripts/releases-ledger.sh` from the PRs and their labels; don't edit
it by hand (the next promotion overwrites it). How promotion works: `docs/plan-deploy.md` §4a.

Every PR is squash-merged into `dev` and deployed to devmargin. Once it's tested there it is
labelled `verified-on-dev`; the **promote-release** workflow cherry-picks verified PRs onto
`release` (prod) in one PR, and labels them `shipped` when that PR is merged. PRs labelled
`needs-flag` ship dark: off in prod until their setting is turned on.

**Starting point.** `release` is at `85b861f` (2026-10-14). The 86 commits on `dev` after it
came from PRs #1–#15 (#12 was closed), merged with merge commits before squash merging was
the rule, so they are not promoted one by one: the first release is a one-time block
promotion (a PR from `dev` into `release`, merged with a merge commit) when the owner
decides; those PRs are then labelled `shipped`. Until then promote-release refuses a later PR that touches the same
files (it may depend on them).

EOF

# Promotions, newest first.
jq -r '
  [ .[] | select(.headRefName | startswith("promote/")) ] | sort_by(.mergedAt) | reverse
  | if length == 0 then "## Promotions\n\nNone yet."
    else "## Promotions\n\n| Promotion | Merged into release | PRs |\n|---|---|---|\n" + (
      map("| #\(.number) | \(.mergedAt[0:10]) | " +
          ((.body // "" | capture("<!-- promote-prs: (?<p>[0-9 ]*) -->").p // "")
            | split(" ") | map(select(. != "") | "#" + .) | join(", ")) + " |")
      | join("\n"))
    end
' "$tmp/release.json"

echo
echo "## PRs merged into dev"
echo
echo "| PR | Title | Merged to dev | Ships dark | Status |"
echo "|---|---|---|---|---|"
jq -r --slurpfile rel "$tmp/release.json" '
  ( [ $rel[0][] | select(.headRefName | startswith("promote/"))
      | . as $p
      | (.body // "" | capture("<!-- promote-prs: (?<p>[0-9 ]*) -->").p // "")
      | split(" ")[] | select(. != "")
      | { key: ., value: "shipped in #\($p.number) (\($p.mergedAt[0:10]))" } ]
    | from_entries ) as $shipped
  | sort_by(.number) | reverse | .[]
  | ([.labels[].name]) as $l
  | "| #\(.number) | \(.title | gsub("\\|"; "\\|")) | \(.mergedAt[0:10]) | "
    + (if $l | index("needs-flag") then "yes" else "" end) + " | "
    + ( $shipped[.number | tostring]
        // (if $l | index("shipped") then "shipped"
            elif $l | index("verified-on-dev") then "verified on dev, not yet promoted"
            else "not yet promoted" end) )
    + " |"
' "$tmp/dev.json"
