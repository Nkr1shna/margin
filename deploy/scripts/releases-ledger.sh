#!/bin/sh
# Writes docs/RELEASES.md to stdout from the release tags (docs/plan-deploy.md §4a). Each
# promotion merged into `release` is tagged release-<date>-<dev short sha> by
# promote-release.yml; the annotated tag's message holds the dev sha, the previous one and
# the PRs it shipped. The ledger is generated from those tags, never hand-edited, so it
# can't drift; promote-release.yml regenerates it after each release.
#
#   git fetch --tags origin && deploy/scripts/releases-ledger.sh > docs/RELEASES.md
#
# Needs only git (run it in a clone with the tags fetched).
set -eu

cat <<'EOF'
# Releases

Generated by `deploy/scripts/releases-ledger.sh` from the `release-*` tags; don't edit it
by hand (the next release overwrites it). How releasing works: `docs/plan-deploy.md` §4a.

Every PR is squash-merged into `dev`, deployed to devmargin and smoke-tested there. A
release promotes one **dev snapshot**: a dev commit whose smoke test passed, with every PR
merged before it. **promote-release** opens a PR into `release` at exactly that commit;
merging it (with a merge commit, never a squash) deploys prod, tags the release and labels
its PRs `shipped`. PRs marked "ships dark" (`needs-flag`) are off in prod until their
setting is turned on.

EOF

tags="$(git for-each-ref --sort=-creatordate --format='%(refname:short)' 'refs/tags/release-*')"
if [ -z "$tags" ]; then
  echo "No releases yet. The first release promotes a dev snapshot like any other."
  exit 0
fi

for t in $tags; do
  msg="$(git for-each-ref --format='%(contents)' "refs/tags/$t")"
  field() { printf '%s\n' "$msg" | sed -n "s/^$1: *//p" | head -n 1; }
  dev="$(field dev-sha)"
  prev="$(field previous-dev-sha)"
  date="$(field released)"
  commit="$(git rev-parse --short=7 "$t^{commit}")"
  echo "## $t"
  echo
  echo "Released ${date:-?} · dev \`$(printf '%.7s' "$dev")\` · release commit \`$commit\`$( [ -z "$prev" ] || printf ' · since dev `%.7s`' "$prev")"
  echo
  printf '%s\n' "$msg" | sed -n '/^PRs:$/,$p' | sed '1d'
  echo
done
