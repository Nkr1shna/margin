/// A file uploaded as a source. The service extracts its text, cuts it into chunks of
/// at most 512 tokens and embeds them with EmbeddingGemma 2; outlines and lessons in
/// its topic get the passages most relevant to what they're writing.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Source {
    pub id: Id,
    /// The topic it belongs to; `None` while it's only attached to an Ask in progress.
    pub topic_id: Option<Id>,
    /// File name, or the path inside the folder it was added with ("notes/ch1.md").
    pub name: String,
    /// The folder's name when it came from a folder, so the app can group it.
    pub folder: Option<String>,
    pub kind: SourceKind,
    /// Size of the uploaded file.
    pub bytes: u64,
    pub status: SourceStatus,
    /// The person whose row this is (L1); `None` only before the `people-v1` migration.
    #[serde(default)]
    pub owner: Option<Id>,
    /// Who may read it: principal ids and group paths (`principal`). Never empty once
    /// written; read empty, it is private to `owner`.
    #[serde(default)]
    pub access: Vec<String>,
    /// Principal ids and group paths refused even when `access` admits them (L2
    /// evaluates it; L1 writes and reads it back).
    #[serde(default)]
    pub deny: Vec<String>,
    pub created_at: DateTime<Utc>,
    /// Signed URL of the original file, for viewing it (images, PDFs, audio, video).
    #[serde(default)]
    pub media_url: Option<String>,
    /// Set for a file of an attached folder: the folder (workspace) it belongs to. Then
    /// `folder` holds the folder's name, `name` the path inside it, and `topic_id` is
    /// `None`; it never belongs to a topic.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub workspace_id: Option<Id>,
    /// The file's modification time on the device that holds it; with `bytes`, the
    /// file's stamp.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub modified: Option<DateTime<Utc>>,
}

/// A numbered reference in a lesson to the source passage it drew on. The lesson body
/// marks it with a Markdown footnote reference `[^n]`; the app lists the citations
/// after the lesson and opens the source at `page` / `start_ms` when one is clicked.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Citation {
    /// 1-based, in order of first appearance in the body.
    pub n: u32,
    pub source_id: Id,
    pub source_name: String,
    pub kind: SourceKind,
    /// PDF page (1-based).
    pub page: Option<u32>,
    /// Where in an audio or video source the passage is.
    pub start_ms: Option<u64>,
    pub end_ms: Option<u64>,
    /// The passage text: a text chunk, a page's text, or the transcript of the clip.
    /// Empty for a bare image.
    pub excerpt: String,
    /// Signed URL of a picture for it: the image itself, the rendered PDF page, or the
    /// video frame.
    pub image_url: Option<String>,
    /// The indexed document the passage is from (`context::Document`); `None` on
    /// citations written before documents existed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub document_id: Option<Id>,
    /// The lines of a text document the passage spans (1-based, inclusive).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start_line: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub end_line: Option<u32>,
    /// Set when the passage is from a file of an attached folder: which folder and which
    /// path (display only; the citation is otherwise an ordinary source citation, and
    /// `source_name` reads "`folder`/`path`").
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub file: Option<WorkspaceFile>,
    /// The section the passage is in, as the chunker named it ("Chapter 2 > Fourier
    /// series"); `None` when it named none, and on citations written before sections.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub section_path: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SourceKind {
    /// Prose: .md, .txt, .rst, .tex, .html, .csv, …
    Text,
    /// Source code, chunked along lines.
    Code,
    /// Text from PDFKit (Vision OCR for pages without text), plus each page as an image.
    Pdf,
    /// .png, .jpg, .heic, .webp, .gif, .tiff, .bmp: embedded with the image encoder.
    Image,
    /// .mp3, .m4a, .wav, .aiff, .flac, .caf: 10-second windows through the audio encoder,
    /// plus a timestamped transcript (FluidAudio speech recognition).
    Audio,
    /// .mp4, .mov, .m4v: sampled frames through the image encoder and the soundtrack as
    /// for audio.
    Video,
}

impl SourceKind {
    /// The kind of source a file is, from its name; `None` for files Margin can't read
    /// (archives, binaries, lock files…).
    pub fn for_name(name: &str) -> Option<SourceKind> {
        let file = name
            .rsplit(['/', '\\'])
            .next()
            .unwrap_or(name)
            .to_ascii_lowercase();
        if file.ends_with(".lock") || file == "package-lock.json" {
            return None;
        }
        const NAMED: &[&str] = &["makefile", "dockerfile", "justfile", "readme", "license"];
        if NAMED.contains(&file.as_str()) {
            return Some(SourceKind::Text);
        }
        let ext = file.rsplit_once('.').map(|(_, e)| e)?;
        const TEXT: &[&str] = &[
            "md", "markdown", "txt", "text", "rst", "adoc", "org", "tex", "bib", "csv", "tsv",
            "html", "htm", "xml", "json", "yaml", "yml", "toml", "ini", "srt", "vtt",
        ];
        const CODE: &[&str] = &[
            "rs", "py", "js", "mjs", "cjs", "ts", "tsx", "jsx", "go", "java", "kt", "kts", "swift",
            "m", "mm", "c", "h", "cc", "cpp", "cxx", "hpp", "cs", "rb", "php", "scala", "hs", "ml",
            "ex", "exs", "erl", "clj", "lua", "r", "jl", "dart", "zig", "nim", "sql", "sh", "bash",
            "zsh", "fish", "ps1", "css", "scss", "vue", "svelte", "proto", "graphql", "ipynb",
        ];
        const IMAGE: &[&str] = &[
            "png", "jpg", "jpeg", "heic", "heif", "webp", "gif", "tif", "tiff", "bmp",
        ];
        const AUDIO: &[&str] = &["mp3", "m4a", "aac", "wav", "aif", "aiff", "flac", "caf"];
        const VIDEO: &[&str] = &["mp4", "mov", "m4v"];
        if ext == "pdf" {
            Some(SourceKind::Pdf)
        } else if IMAGE.contains(&ext) {
            Some(SourceKind::Image)
        } else if AUDIO.contains(&ext) {
            Some(SourceKind::Audio)
        } else if VIDEO.contains(&ext) {
            Some(SourceKind::Video)
        } else if TEXT.contains(&ext) {
            Some(SourceKind::Text)
        } else if CODE.contains(&ext) {
            Some(SourceKind::Code)
        } else {
            None
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum SourceStatus {
    /// Waiting to be read (or for the embedding model to be downloaded).
    Queued,
    /// Extracting text and embedding chunks; `done` of `total` chunks so far.
    Processing {
        done: u32,
        total: u32,
    },
    Ready {
        chunks: u32,
        pages: Option<u32>,
        /// Read, but not all of it: e.g. a recording that couldn't be transcribed (its
        /// sound is embedded, but lessons can't quote it). The app shows it with a
        /// "Read again" action (`routes::source_reprocess`).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        warning: Option<String>,
    },
    Failed {
        error: String,
    },
}

impl SourceStatus {
    /// Whether "Read again" can help: it failed, or it was read with a warning.
    pub fn can_read_again(&self) -> bool {
        matches!(
            self,
            SourceStatus::Failed { .. }
                | SourceStatus::Ready {
                    warning: Some(_),
                    ..
                }
        )
    }
}

