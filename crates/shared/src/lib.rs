//! The contract between the Margin service and its apps: stored records,
//! request and response bodies, live events, and route paths.
//!
//! Every type here crosses the network as JSON. Field names are the wire
//! format, so renaming one is a breaking change for every installed app.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

pub mod routes;

/// Serde for `Option<Option<T>>` patch fields: a missing field is `None` (unchanged),
/// `null` is `Some(None)` (clear), and a value is `Some(Some(v))`. Use with
/// `#[serde(default, skip_serializing_if = "Option::is_none", with = "double_option")]`.
mod double_option {
    use serde::{Deserialize, Deserializer, Serialize, Serializer};

    pub fn serialize<T: Serialize, S: Serializer>(
        value: &Option<Option<T>>,
        serializer: S,
    ) -> Result<S::Ok, S::Error> {
        match value {
            Some(inner) => inner.serialize(serializer),
            None => serializer.serialize_none(),
        }
    }

    pub fn deserialize<'de, T: Deserialize<'de>, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<Option<Option<T>>, D::Error> {
        Option::<T>::deserialize(deserializer).map(Some)
    }
}

/// A record identifier. Generated by the service (UUID v4 text); apps never mint ids.
pub type Id = String;

// ---------------------------------------------------------------------------
// Library records
