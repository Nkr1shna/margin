/// A node in the topic tree. Root topics (`parent_id == None`) are subjects such as
/// "Signals & Systems"; their children are topics such as "Fourier series", which own
/// lessons and notes. Any depth is allowed; the sidebar renders the tree as stored.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Topic {
    pub id: Id,
    pub parent_id: Option<Id>,
    pub title: String,
    /// Sort order among siblings, ascending.
    pub position: i64,
    /// The person whose row this is (L1); `None` only before the `people-v1` migration.
    #[serde(default)]
    pub owner: Option<Id>,
    /// Who may read it: principal ids and group paths (`principal`). Never empty once
    /// written; read empty, it is private to `owner`.
    #[serde(default)]
    pub access: Vec<String>,
    /// Principal ids and group paths refused even when `access` admits them (L2
    /// evaluates it; L1 writes and reads it back).
    #[serde(default)]
    pub deny: Vec<String>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

