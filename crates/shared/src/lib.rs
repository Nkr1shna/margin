// `SettingsChanged` carries the whole `Settings` (three providers' slots): events are
// short-lived and sent once, so its size isn't worth boxing the wire type for.
#[allow(clippy::large_enum_variant)]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Event {
    /// Sent once right after the socket opens.
    Hello {
        server_version: String,
    },
    TopicChanged {
        topic: Topic,
    },
    TopicDeleted {
        id: Id,
    },
    LessonChanged {
        lesson: Lesson,
    },
    /// Text appended to a generating lesson's body. Apply in order; a following
    /// `LessonChanged` carries the authoritative full body.
    LessonDelta {
        lesson_id: Id,
        text: String,
    },
    LessonDeleted {
        id: Id,
    },
    NoteChanged {
        note: Note,
    },
    NoteDeleted {
        id: Id,
    },
    VideoChanged {
        video: Video,
    },
    VideoDeleted {
        id: Id,
    },
    ProposalChanged {
        proposal: Proposal,
    },
    SettingsChanged {
        settings: Settings,
    },
    SourceChanged {
        source: Source,
    },
    SourceDeleted {
        id: Id,
    },
    EmbeddingModelChanged {
        model: EmbeddingModel,
    },
    /// A chat was created or its title, state, attachments, pending message or usage
    /// changed. Carries the whole chat.
    ChatChanged {
        chat: Chat,
    },
    ChatDeleted {
        id: Id,
    },
    /// An item was added, or finished, or changed (status, label, card decision). The
    /// item is authoritative: it replaces whatever deltas built.
    ChatItemChanged {
        item: ChatItem,
    },
    /// Text appended to an `InProgress` item: `AssistantText.text`,
    /// `Reasoning.summary` or `ToolCall.arguments`. `offset` is the length in bytes of
    /// that text before this delta, so a device that loaded the chat mid-stream can tell
    /// a delta it already has from one it missed (`ChatItemKind::apply_delta`). The
    /// following `ChatItemChanged` carries the full value.
    ChatItemDelta {
        chat_id: Id,
        item_id: Id,
        offset: u64,
        text: String,
    },
    WorkspaceChanged {
        workspace: Workspace,
    },
    WorkspaceDeleted {
        id: Id,
    },
    /// A device came online or went offline, or was renamed.
    DeviceChanged {
        device: Device,
    },
    /// A device was revoked.
    DeviceDeleted {
        id: Id,
    },
    /// A document was indexed again (its `generation` went up) or its status changed.
    DocumentChanged {
        document: context::Document,
    },
    /// A trace row, sent only to sockets that subscribed with `?traces=1` (admins only).
    Trace {
        row: Box<context::TraceRow>,
    },
    /// A person was invited in, edited, enabled or disabled (L1). Carries the whole
    /// person; `settings` only to the person themself.
    PersonChanged {
        person: Person,
    },
    /// A group was created or renamed.
    GroupChanged {
        group: Group,
    },
    GroupDeleted {
        path: String,
    },
    /// A person's direct memberships were replaced.
    MembershipChanged {
        person_id: Id,
        groups: Vec<String>,
    },
    /// An agent was created or changed (to its owner and admins).
    AgentChanged {
        agent: Agent,
    },
    AgentDeleted {
        id: Id,
    },
    /// An invitation was made, accepted or revoked (to admins).
    InvitationChanged {
        invitation: Invitation,
    },
    InvitationDeleted {
        id: Id,
    },
    /// What `person_id` may read changed (memberships, role): reload the library.
    AccessChanged {
        person_id: Id,
    },
}

/// Error body for every non-2xx API response.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ApiError {
    /// Stable machine code, e.g. "unauthorized", "not_found", "no_api_key".
    pub code: String,
    /// Human-readable sentence suitable for showing in the app.
    pub message: String,
}

