// ---------------------------------------------------------------------------
// Sign-in ("the app waits on the service")
// ---------------------------------------------------------------------------
//
// 1. App: POST /auth/start {device_name} -> StartLogin.
// 2. App opens `authorize_url` in the system browser (GitHub OAuth, state = login_id).
// 3. GitHub redirects to the service's /auth/github/callback; the service checks the
//    GitHub login against its allowlist and, if allowed, mints a device token.
// 4. App: POST /auth/poll {login_id, poll_secret} every 2 s until not Pending.
// Logins expire 10 minutes after start.

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StartLoginRequest {
    pub device_name: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StartLogin {
    pub login_id: Id,
    /// Secret only the starting app knows; required to collect the token.
    pub poll_secret: String,
    pub authorize_url: String,
    pub expires_at: DateTime<Utc>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PollLoginRequest {
    pub login_id: Id,
    pub poll_secret: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum LoginState {
    Pending,
    /// Returned exactly once; later polls return `Expired`.
    Approved {
        token: String,
        github_login: String,
    },
    Denied {
        reason: String,
    },
    Expired,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Me {
    pub github_login: String,
    pub device: Device,
}

// ---------------------------------------------------------------------------
// Live events, sent over the /api/events WebSocket as JSON text frames
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Event {
    /// Sent once right after the socket opens.
    Hello {
        server_version: String,
    },
    TopicChanged {
        topic: Topic,
    },
    TopicDeleted {
        id: Id,
    },
    LessonChanged {
        lesson: Lesson,
    },
    /// Text appended to a generating lesson's body. Apply in order; a following
    /// `LessonChanged` carries the authoritative full body.
    LessonDelta {
        lesson_id: Id,
        text: String,
    },
    LessonDeleted {
        id: Id,
    },
    NoteChanged {
        note: Note,
    },
    NoteDeleted {
        id: Id,
    },
    VideoChanged {
        video: Video,
    },
    VideoDeleted {
        id: Id,
    },
    ProposalChanged {
        proposal: Proposal,
    },
    SettingsChanged {
        settings: Settings,
    },
    SourceChanged {
        source: Source,
    },
    SourceDeleted {
        id: Id,
    },
    EmbeddingModelChanged {
        model: EmbeddingModel,
    },
}

/// Error body for every non-2xx API response.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ApiError {
    /// Stable machine code, e.g. "unauthorized", "not_found", "no_api_key".
    pub code: String,
    /// Human-readable sentence suitable for showing in the app.
    pub message: String,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn patch_fields_distinguish_unchanged_from_clear() {
        let unchanged = TopicPatch::default();
        assert!(
            !serde_json::to_string(&unchanged)
                .unwrap()
                .contains("parent_id")
        );
        let back: TopicPatch = serde_json::from_str("{}").unwrap();
        assert_eq!(back.parent_id, None);

        let to_root = TopicPatch {
            parent_id: Some(None),
            ..Default::default()
        };
        let json = serde_json::to_string(&to_root).unwrap();
        assert!(json.contains(r#""parent_id":null"#), "{json}");
        assert_eq!(
            serde_json::from_str::<TopicPatch>(&json).unwrap().parent_id,
            Some(None)
        );

        let moved = TopicPatch {
            parent_id: Some(Some("t1".into())),
            ..Default::default()
        };
        let json = serde_json::to_string(&moved).unwrap();
        assert_eq!(
            serde_json::from_str::<TopicPatch>(&json).unwrap().parent_id,
            Some(Some("t1".into()))
        );

        let clear_voice = SettingsPatch {
            voice: Some(None),
            ..Default::default()
        };
        let json = serde_json::to_string(&clear_voice).unwrap();
        assert_eq!(
            serde_json::from_str::<SettingsPatch>(&json).unwrap().voice,
            Some(None)
        );
        assert_eq!(
            serde_json::from_str::<SettingsPatch>("{}").unwrap().voice,
            None
        );
    }
}
