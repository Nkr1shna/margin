#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AskRequest {
    /// What the learner wants to learn, in their own words.
    pub prompt: String,
    /// Number of lessons to propose, 1..=12.
    pub lesson_count: u32,
    pub level: Level,
    pub with_videos: bool,
    pub with_quiz: bool,
    /// Subject to file the new topic under; `None` lets the model pick or create one.
    pub parent_topic_id: Option<Id>,
    /// Uploaded sources (`Source.id`, not yet attached to a topic) the outline and the
    /// lessons draw on. Accepting the proposal attaches them to the new topic.
    #[serde(default)]
    pub source_ids: Vec<Id>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct OutlineLesson {
    pub title: String,
    pub summary: String,
    pub minutes: u32,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Outline {
    /// Title of the new topic, e.g. "Fourier series".
    pub topic_title: String,
    /// Title of the subject to file it under when `AskRequest.parent_topic_id` is None.
    /// The service reuses an existing root topic with the same title (case-insensitive).
    pub subject_title: String,
    pub lessons: Vec<OutlineLesson>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum ProposalStatus {
    Drafting,
    Ready,
    /// Accepted; `topic_id` is the topic that was created.
    Accepted {
        topic_id: Id,
    },
    Failed {
        error: String,
    },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Proposal {
    pub id: Id,
    pub request: AskRequest,
    pub status: ProposalStatus,
    pub outline: Option<Outline>,
    pub created_at: DateTime<Utc>,
}

/// Accept a proposal, optionally with an edited outline.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
