/// A node in the topic tree. Root topics (`parent_id == None`) are subjects such as
/// "Signals & Systems"; their children are topics such as "Fourier series", which own
/// lessons and notes. Any depth is allowed; the sidebar renders the tree as stored.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Topic {
    pub id: Id,
    pub parent_id: Option<Id>,
    pub title: String,
    /// Sort order among siblings, ascending.
    pub position: i64,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Level {
    Intro,
    Intermediate,
    Advanced,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum LessonStatus {
    /// Created from an accepted outline; generation has not started.
    Queued,
    /// The body is streaming in; `LessonDelta` events carry new text.
    Generating,
    Ready,
    Failed {
        error: String,
    },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Lesson {
    pub id: Id,
    pub topic_id: Id,
    pub title: String,
    /// One-line description from the outline.
    pub summary: String,
    pub position: i64,
    pub level: Level,
    /// Estimated reading time in minutes.
    pub minutes: u32,
    /// Markdown. Math uses `$…$` and `$$…$$`. Ends with a "Check yourself" section
    /// when the lesson was generated with a quiz.
    pub body_md: String,
    pub status: LessonStatus,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

/// A note. Margin notes carry the lesson text they were taken from in `quote`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Note {
    pub id: Id,
    pub topic_id: Id,
    pub lesson_id: Option<Id>,
    pub title: String,
    pub body_md: String,
    /// The selected lesson text this note annotates, if it is a margin note.
    pub quote: Option<String>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "state", rename_all = "snake_case")]
pub enum VideoStatus {
    Queued,
    /// The model is writing the ManimGX scene.
    Scripting,
    /// Narration lines are being voiced with PocketTTS.
    Voicing {
        done: u32,
        total: u32,
    },
    /// ManimGX is rendering. `progress` is 0.0..=1.0 when known.
    Rendering {
        progress: Option<f32>,
    },
    Ready,
    Failed {
        error: String,
    },
}

/// One video per lesson. Re-rendering replaces the files and keeps the id.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Video {
    pub id: Id,
    pub lesson_id: Id,
    pub status: VideoStatus,
    /// The ManimGX scene source (Python) the model wrote, shown read-only in the app.
    pub scene_code: Option<String>,
    /// Tail of the render log (last ~200 lines).
    pub log: String,
    pub duration_seconds: Option<f32>,
    /// Signed, short-lived URLs filled in by the service on every response that
    /// carries a Ready video. Never stored.
    pub media: Option<VideoMedia>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VideoMedia {
    /// MP4, supports HTTP range requests. Absolute URL.
    pub mp4_url: String,
    /// Storyboard PNG written by ManimGX. Absolute URL.
    pub storyboard_url: String,
    /// Captions (.srt), when the scene speaks. Absolute URL.
    pub captions_url: Option<String>,
    /// The video's thumbnail: the scene's closing poster shot as a PNG at full render
    /// size. Absolute URL. `None` for videos rendered before posters existed.
    #[serde(default)]
    pub poster_url: Option<String>,
    pub expires_at: DateTime<Utc>,
}

